"""Robot profile schema (spec section 22).

A profile is a YAML file that maps capabilities to a robot's actual ROS
interfaces. This is the schema the agent validates it against. Writing a
profile is how ringfour is ported to a new robot; the agent itself knows
no robot.

Validation philosophy: strict about what the current phases consume
(identity, frames, section shapes), tolerant of extra keys (a profile may
carry config for phases that are not implemented yet). Unknown top-level
sections are rejected so typos don't silently disable a capability.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    field_validator,
    model_validator,
)

# Absolute, and from the SDK on purpose. The enums are WIRE vocabulary —
# Controller, GroupKind, Locomotion cross the socket and both sides must
# agree on the strings — so they stay in ringfour even though the schema
# that uses them is the agent's.
from ringfour.enums import Controller, GroupKind, Locomotion

# Capability registry, spec section 4. A profile section with one of these
# names declares that capability; report order is this order.
KNOWN_CAPABILITIES = (
    "mobility",
    "groups",
    "sensors",
    "actions",
    "cameras",
    "lidar",
    "range_sensors",
    "imu",
    "force_torque",
    "environment",
    "slam",
    "exploration",
    "teleop",
    "control",
    "watches",
    "places",
    "audit",
    "status",
    "power",
)

# Sections that used to be capabilities and are not any more. Kept as a
# lookup so a stale profile fails with "use groups: instead" rather than
# with pydantic's generic "extra inputs are not permitted".
RETIRED_SECTIONS = {
    "manipulation": "groups (one entry per arm, kind: arm)",
    "joint_groups": "groups (one entry each, kind: pointing|linear)",
}

# Top-level profile keys that are not capabilities.
STRUCTURAL_KEYS = ("name", "model", "version", "protocol", "frames", "safety",
                   "joint_states")


# Keys that would name a description file. Rejected in EVERY section, not
# just at the top level (spec 26.2: "never a file path, no offline mode").
# The extra="allow" below exists so a profile can carry config for phases
# that are not implemented yet — which is precisely the loophole a `urdf:`
# would slip through, and a group is where someone porting an arm would
# most naturally put one.
#
# The rule is not pedantry. mod101's URDF is generated by the
# configurator, so a path can describe a different arm than the one
# bolted on, and for a composed robot it cannot be accurate at all.
FORBIDDEN_DESCRIPTION_KEYS = frozenset({
    "urdf", "urdf_path", "urdf_file", "description_file", "srdf",
})


class _Section(BaseModel):
    """Base for profile sections: frozen, extra keys allowed (config for
    future phases rides along without schema churn) — except a file path
    to a description, which is never allowed anywhere."""

    model_config = ConfigDict(frozen=True, extra="allow")

    @model_validator(mode="after")
    def _no_description_files(self) -> "_Section":
        named = FORBIDDEN_DESCRIPTION_KEYS & set(self.model_extra or {})
        if named:
            raise ValueError(
                f"{', '.join(sorted(named))}: a profile never points at a "
                f"description file. The agent reads /robot_description "
                f"live (spec 26.2) - a path can silently describe a "
                f"different robot than the one moving. Use "
                f"`description_topic:` on a group if a namespaced launch "
                f"publishes it somewhere other than /robot_description.")
        return self


class FramesConfig(_Section):
    """TF frame names this robot uses; aliases @map/@odom/@base resolve here."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    map: str
    odom: str
    base: str


class MobilityConfig(_Section):
    locomotion: Locomotion
    cmd_vel: str | None = None
    # Message type the cmd_vel sink expects. TwistStamped on Jazzy
    # (diff_drive_controller and twist_mux with use_stamped both moved to
    # it); set False for stacks that take plain geometry_msgs/Twist.
    cmd_vel_stamped: bool = True
    odom_topic: str | None = None
    nav2_navigate_to_pose: str | None = None
    nav2_follow_waypoints: str | None = None
    max_linear: float | None = None   # m/s, server-side safety clamp
    max_angular: float | None = None  # rad/s
    arrival_position_tolerance: float = Field(default=.1, gt=0, allow_inf_nan=False)  # m, full 3D
    arrival_orientation_tolerance: float = Field(default=.1, gt=0, allow_inf_nan=False)  # rad


class ToolConfig(_Section):
    """The end-effector fitted to a group (spec 8.3).

    ``type`` is free text describing the mechanism ("jaws", "parallel",
    "suction"); the agent does not branch on it, it is reported so a
    mission can. ``joint`` is the single actuated joint the tool
    controller commands.

    ``joint`` is validated against the ``<ros2_control>`` declarations as
    well as the kinematic tree, because a tool joint need only be in the
    former: a gripper can be commandable without its fingers being
    modelled, and that is a robot's choice to make, not a reason to refuse
    to boot.
    """

    type: str
    joint: str | None = None
    open: float | None = None    # meters (or radians), fully open
    closed: float | None = None  # meters (or radians), fully closed


class WorkspaceConfig(_Section):
    """Server-side reachability box for a group, in the robot's base frame.

    A non-bypassable clamp (spec 21), not a hint: a target outside the box
    is rejected before any controller sees it. ``None`` means unclamped,
    which is the right default only for a group that cannot reach anything
    dangerous.
    """

    # {"x": (lo, hi), "y": ..., "z": ...} in meters. Axes may be omitted
    # individually; an omitted axis is unclamped.
    box: dict[str, tuple[float, float]] | None = None

    @field_validator("box")
    @classmethod
    def _ordered_and_known_axes(
        cls, box: dict[str, tuple[float, float]] | None,
    ) -> dict[str, tuple[float, float]] | None:
        if box is None:
            return None
        for axis, (lo, hi) in box.items():
            if axis not in ("x", "y", "z"):
                raise ValueError(
                    f"workspace box axis {axis!r} is not one of x, y, z")
            if lo > hi:
                raise ValueError(
                    f"workspace box {axis}: [{lo}, {hi}] is inverted")
        return box


class JointStopPolicy(_Section):
    """Integrator-reviewed measured-rest thresholds, never morphology guesses.

    Angular and linear limits use distinct units. Missing limits cannot verify
    joints of that type. Dwell and timeout are explicit deployment policy.
    """
    angular_velocity_limit: float | None = None
    linear_velocity_limit: float | None = None
    dwell: float
    timeout: float = Field(le=15)

    @field_validator("angular_velocity_limit", "linear_velocity_limit", "dwell", "timeout", mode="before")
    @classmethod
    def _finite_positive(cls, value):
        import math
        if value is None: return value
        if type(value) not in (int, float) or not math.isfinite(value) or value <= 0:
            raise ValueError("stop thresholds and budgets must be positive finite numbers")
        return value

    @model_validator(mode="after")
    def _budget(self):
        if self.timeout <= self.dwell:
            raise ValueError("stop timeout must exceed dwell")
        if self.angular_velocity_limit is None and self.linear_velocity_limit is None:
            raise ValueError("declare an angular or linear stop velocity limit")
        return self


class GroupConfig(_Section):
    """One actuated structure: an arm, a pan/tilt head, a torso lift, a leg.

    Replaces v0.4's ``manipulation.arms.<name>`` and ``joint_groups.<name>``
    (spec 8.6) - the split is gone, an arm is just a group that declares a
    tip and a tool.

    Porting a group needs three things: ``kind``, ``controllers.trajectory``,
    and - if you want IK - ``tip``. Everything else is derived: joint names
    come from the controller's claimed interfaces, limits and geometry come
    from the description.

    No ``named_poses`` (decision 5, 2026-08-23): joint vectors in YAML are
    not portable, and a mission that wants "home" writes the vector where it
    can be seen.
    """

    kind: GroupKind
    # The frame IK solves to. None disables IK for this group - that is the
    # gate, not an error: a lift or a head has nothing meaningful to reach
    # with. Must exist in the description and sit downstream of the joints.
    tip: str | None = None
    # Which Cartesian DOF the chain can actually control, [x, y, z, rx, ry,
    # rz]. A 5-DOF arm cannot hold a full pose, and saying so here is what
    # lets the solver reject an over-constrained target instead of
    # converging on a lie.
    dof_mask: tuple[int, ...] | None = None
    # Role -> controller name. TRAJECTORY is required; STREAM and TOOL are
    # optional. The trajectory twin is typically declared-but-unloaded (see
    # 6.0b) - the agent loads it at session entry.
    controllers: dict[Controller, str]
    # Optional override of the joints, in kinematic order. Default: the
    # claimed interfaces of whichever of the group's controllers is loaded.
    # Kept because it feeds group.joints and the watch paths.
    joints: tuple[str, ...] = ()
    tool: ToolConfig | None = None
    workspace: WorkspaceConfig | None = None
    # kind: pointing only - the frame that gets aimed by kin.point_at().
    pointing_frame: str | None = None
    # Namespaced launches publish the description somewhere else.
    description_topic: str | None = None
    # How far a joint may be from its final waypoint and still count as
    # ARRIVED, in radians (or metres for a prismatic joint).
    #
    # WHY THIS EXISTS. A JointTrajectoryController reports `succeeded`
    # when it finishes executing its plan, which is NOT the same as the
    # joints being where the plan ended: give a trajectory less time than
    # the joint needs and the controller interpolates to the end of its
    # schedule, stops, and succeeds — with the arm somewhere else. On a
    # multi-joint move each joint stops at a different fraction of its
    # travel, so the tip lands nowhere near the target while every layer
    # reports success. That cost a day on 2026-09-01; see
    # docs/journal/found_along_the_way.md section 16.
    #
    # Absolute error in each joint's native URDF units: radians for
    # revolute/continuous joints, metres for prismatic joints. Choose the
    # value for the group's required accuracy; it is not morphology-specific.
    goal_tolerance: float = 0.05
    goal_tolerances: dict[str, float] = {}
    feedback_max_age: float = 0.5
    stop_verification: JointStopPolicy | None = None

    @field_validator("goal_tolerance", "feedback_max_age")
    @classmethod
    def _positive_feedback_policy(cls, value):
        import math
        if not math.isfinite(value) or value <= 0:
            raise ValueError("feedback ages and arrival tolerances must be positive and finite")
        return value

    @field_validator("goal_tolerances")
    @classmethod
    def _per_joint_tolerances(cls, values):
        for value in values.values():
            cls._positive_feedback_policy(value)
        return values

    @field_validator("controllers", mode="after")
    @classmethod
    def _named_and_movable(
        cls, controllers: dict[Controller, str],
    ) -> dict[Controller, str]:
        """Require a trajectory controller and canonicalise the names.

        ros2_control identifies controllers WITHOUT a leading slash
        (``arm_controller``), but profiles have always been written with one
        because every other value in the file is a topic. Both are accepted
        and stored stripped, so nothing downstream has to remember which
        spelling it got.
        """
        if Controller.TRAJECTORY not in controllers:
            raise ValueError(
                "controllers must include 'trajectory' - it is the role "
                "every motion verb resolves to; got "
                f"{sorted(str(role) for role in controllers)}")
        stripped = {role: name.lstrip("/")
                    for role, name in controllers.items()}
        for role, name in stripped.items():
            if not name:
                raise ValueError(f"controllers.{role} is empty")
        return stripped

    @field_validator("dof_mask")
    @classmethod
    def _six_flags(cls, mask: tuple[int, ...] | None) -> tuple[int, ...] | None:
        if mask is None:
            return None
        if len(mask) != 6:
            raise ValueError(
                f"dof_mask must have 6 entries [x, y, z, rx, ry, rz], "
                f"got {len(mask)}")
        if any(flag not in (0, 1) for flag in mask):
            raise ValueError(f"dof_mask entries must be 0 or 1, got {mask!r}")
        return mask

    @model_validator(mode="after")
    def _kind_consistency(self) -> "GroupConfig":
        if self.kind is GroupKind.POINTING and not self.pointing_frame:
            raise ValueError(
                "kind: pointing needs pointing_frame - the frame to aim")
        if self.pointing_frame and self.kind is not GroupKind.POINTING:
            raise ValueError(
                f"pointing_frame is only meaningful on kind: pointing, "
                f"not kind: {self.kind}")
        # A tool and a tool controller are two halves of one thing: the
        # config says what the mechanism is, the controller is how it is
        # commanded. Either alone is a profile that half-declares a gripper.
        has_role = Controller.TOOL in self.controllers
        if self.tool is not None and not has_role:
            raise ValueError(
                "tool: declared without controllers.tool - nothing can "
                "command it")
        if has_role and self.tool is None:
            raise ValueError(
                "controllers.tool is declared without a tool: section - "
                "add one naming the mechanism and its joint")
        return self

    @property
    def controller_names(self) -> tuple[str, ...]:
        """Every controller this group claims, deduplicated, in role order."""
        seen: dict[str, None] = {}
        for role in Controller:
            name = self.controllers.get(role)
            if name is not None:
                seen[name] = None
        return tuple(seen)


class SensorSignal(_Section):
    """One scalar a vendor publishes, bound to a name (spec: sensors).

    The escape hatch for anything on a topic that the capability registry
    does not already cover — servo temperature, bus voltage, a load cell.
    Read-only by construction: a signal is subscribed, never written.

    ``type`` is a ROS type name resolved at runtime, so the agent needs no
    per-vendor code. ``field`` digs into a compound message; leave it out
    for the single-field messages most telemetry uses.
    """

    topic: str
    type: str = "std_msgs/Float32"
    # Dotted path into the message. None means "the message has one
    # obvious field" - `data` on the std_msgs scalars.
    field: str | None = None
    # Reported, never converted. Int32 celsius sitting beside Float32
    # milliamps is exactly the pair that misleads silently, and a library
    # that quietly rescaled would be worse than one that just says.
    units: str | None = None


class ActionParameter(_Section):
    """One argument a vendor action accepts."""

    type: Literal["float", "int", "bool", "string"] = "float"
    min: float | None = None
    max: float | None = None
    default: Any = None


class ActionConfig(_Section):
    """One thing a vendor lets you command (spec: actions).

    The write half of the escape hatch: an LED, a horn, a fan, an
    outrigger. Published on request, audited like any other command, and
    rate-limited because an arbitrary topic is otherwise a hole straight
    through to the robot's DDS.
    """

    topic: str
    type: str
    # REQUIRED, deliberately with no default. Neither default is safe:
    # `true` makes every LED author write `is_motion: false`, which they
    # will then cargo-cult onto something that does move; `false` lets a
    # brake release through unguarded. Requiring it costs one line and
    # forces the thought once, at the only moment anyone has the context
    # to answer it.
    is_motion: bool
    # Explicit stop publication and observable footprint for opaque motion.
    motion_resource: str | None = None  # mobility or group:<declared name>
    stop_arguments: dict[str, Any] | None = None
    # Server-side ceiling on how often a client may invoke this.
    max_rate: float = 10.0
    parameters: dict[str, ActionParameter] = {}

    @model_validator(mode="after")
    def _defaults_are_in_range(self) -> "ActionConfig":
        for name, spec in self.parameters.items():
            if spec.default is None:
                continue
            if not isinstance(spec.default, (int, float, bool, str)):
                raise ValueError(
                    f"parameters.{name}.default must be a scalar")
            if isinstance(spec.default, (int, float)) and not isinstance(
                    spec.default, bool):
                if spec.min is not None and spec.default < spec.min:
                    raise ValueError(
                        f"parameters.{name}: default {spec.default} is "
                        f"below min {spec.min}")
                if spec.max is not None and spec.default > spec.max:
                    raise ValueError(
                        f"parameters.{name}: default {spec.default} is "
                        f"above max {spec.max}")
        return self


class CameraConfig(_Section):
    rgb: str | None = None
    depth: str | None = None
    info: str | None = None
    # Optional PointCloud2 topic. Accepted now so profiles can declare
    # it; v1 clouds are computed from depth (the PointField parser is
    # deferred until a robot needs it — see the Phase 4 worklog).
    cloud: str | None = None
    # TF frame the camera's data is expressed in. Default: the frame_id
    # from the camera_info header. ``optical: true`` says that frame
    # already follows the ROS optical convention (z forward, x right,
    # y down); false means it is the physical link (x forward, REP 103)
    # and the agent applies the fixed optical->link rotation when
    # deprojecting.
    frame: str | None = None
    optical: bool = False
    # How long deprojection handles stay valid (spec Q6, resolved by
    # Cristi 2026-06-12: 30 s default — sized for a cloud VLM round
    # trip — per-profile override here).
    frame_ttl: float = 30.0

    # How far apart an rgb and a depth message may be stamped and still count
    # as one synced pair (get_synced / deproject / get_cloud). None keeps the
    # agent default. Raise it for a camera whose two streams are genuinely
    # not captured together; do NOT raise it to paper over a stalling sensor,
    # because the whole value of the frame handle is that rgb, depth and the
    # TF snapshot came from one instant.
    sync_tolerance: float | None = None
    # Server-side cap on camera.stream rates (clients may request lower,
    # never higher).
    max_stream_fps: float = 15.0


