class LeasePolicy(_Section):
    """Explicit integrator timing policy; no implied hard real-time guarantee."""
    model_config = ConfigDict(frozen=True, extra="forbid")
    lifetime: float
    renew_interval: float

    @field_validator("lifetime", "renew_interval", mode="before")
    @classmethod
    def _positive(cls, value):
        import math
        if type(value) not in (int, float) or not math.isfinite(value) or value <= 0:
            raise ValueError("lease budgets must be positive finite numbers")
        return value

    @model_validator(mode="after")
    def _budget(self):
        if self.renew_interval >= self.lifetime / 2:
            raise ValueError("renew_interval must be less than half the lease lifetime")
        return self


class SafetyConfig(_Section):
    # Explicit reviewed post-boot controller baseline; never inferred from
    # whichever controllers happen to be active after an unclean exit.
    restart_recovery_controllers: dict[str, Literal['active','inactive','unconfigured']] | None = None
    lease: LeasePolicy | None = None
    # Shared native-unit measured-rest contract; group overrides are optional.
    stop_verification: JointStopPolicy | None = None
    feedback_max_age: float = Field(default=.5, gt=0, allow_inf_nan=False)
    stop_on_disconnect: bool = False
    confirm_required: tuple[str, ...] = ()


